"""Build the control materials for Phase-4 ② (length-matched) and ⑤ (randomized K).

  build      filler chunks (same-article non-results prose, token-matched to the
             article's multi material) + K-dose distractor pools + paraphrase
             REQUESTS; paraphrases are generated by GPT-5.4-mini here as well
  verify     run the frozen evaluator on every paraphrase; keep those from which
             it recovers the gold label (same criterion targets had to pass);
             needs the 32B evaluator server (port 8301)

Output: data/phase4/materials.jsonl, one row per gate2_v1 article:
  sample_id, K, filler_chunks [K-1], dup_chunks [K-1 verified paraphrases],
  dup_candidates (all, with verdicts), kpool [permuted extra distractors]
Token matching uses o200k_base as the fixed reference tokenizer, so the
material is identical for every generator model.
"""
import argparse
import asyncio
import html
import json
import random
import re
import sys
from pathlib import Path

import pandas as pd
import tiktoken

sys.path.insert(0, str(Path(__file__).resolve().parents[1]))
from supdrift.llm import LLMCache, chat, full_cache_key  # noqa: E402

SEED = 42
OUT = Path("data/phase4/materials.jsonl")
FULLTEXT = Path("data/fulltext")
ENC = tiktoken.get_encoding("o200k_base")
LABEL_MAP = {"significantly increased": "INCREASE", "no significant difference": "NO_DIFFERENCE",
             "significantly decreased": "DECREASE"}
# a filler sentence must not carry a finding: no numbers, no effect language
FINDING_RE = re.compile(r"\d|%|\bp\s*[<>=]|significan|increas|decreas|reduc|improv|higher|lower|"
                        r"greater|smaller|better|worse|effective|efficac|associat|correlat|"
                        r"differen|compared|versus|\bvs\b", re.I)
PARA_SYSTEM = """You rewrite excerpts from clinical study reports.
Paraphrase the excerpt so that every finding is preserved exactly: same outcomes,
same direction of effect, same numbers, same statistical statements (including
"no significant difference"). Change only wording and sentence structure.
Do not add, drop, or hedge anything. Output only the paraphrase."""
PARA_USER = "Excerpt:\n{text}\n\nParaphrase it in about {words} words."


def ntok(text):
    return len(ENC.encode(text, disallowed_special=()))


def prose_ratio(t):
    return sum(c.isalpha() or c in " ,.;:()%-" for c in t) / len(t) if t else 0.0


# ------------------------------------------------------------------ filler
def filler_sentences(pmcid):
    """Sentences from BODY sections before the first Results heading, with any
    sentence that could carry a finding removed."""
    p = FULLTEXT / f"PMC{pmcid}.txt"
    if not p.exists():
        return []
    keep, section = [], None
    for line in open(p, encoding="utf-8", errors="ignore"):
        m = re.match(r"^\s*([A-Z][A-Z .&/,()-]+):\s*$", line)
        if m:
            section = m.group(1).strip()
            continue
        if section is None or not section.startswith("BODY."):
            continue
        if re.search(r"RESULT|DISCUSS|CONCLUS|FINDING|OUTCOME", section):
            break
        text = re.sub(r"\s+", " ", html.unescape(line)).strip()
        for s in re.split(r"(?<=[.!?])\s+(?=[A-Z(])", text):
            s = s.strip()
            if 60 <= len(s) <= 400 and prose_ratio(s) >= 0.85 and not FINDING_RE.search(s):
                keep.append(s)
    return keep


def make_filler(sample, rng):
    """(K-1) chunks; chunk i is token-matched to distractor i. Sentences are
    used whole and never reused; each chunk is filled best-fit from a shuffled
    pool so the total lands within +-10% (+8 tokens) of the distractor total."""
    sents = filler_sentences(sample["pmcid"])
    targets = [ntok(d["evidence"]) for d in sample["distractors"]]
    pool = [(s, ntok(s)) for s in sents]
    rng.shuffle(pool)
    if sum(n for _, n in pool) < sum(targets):        # not enough prose
        return None
    chunks = []
    for want in targets:
        parts, have = [], 0
        while pool and have < want - 4:
            # largest sentence that still fits the remainder (+ small slack),
            # else the shortest one available
            fits = [p for p in pool if p[1] <= want - have + 6]
            pick = max(fits, key=lambda p: p[1]) if fits else min(pool, key=lambda p: p[1])
            pool.remove(pick)
            parts.append(pick[0]); have += pick[1]
        if not parts:
            return None
        chunks.append(" ".join(parts))
    got, want = sum(ntok(c) for c in chunks), sum(targets)
    if abs(got - want) > 0.10 * want + 8:
        return None
    return chunks


# ------------------------------------------------------------------ K pool
def build_kpools(samples):
    ann = pd.read_csv("data/raw/annotations_merged.csv")
    prompts = pd.read_csv("data/raw/prompts_merged.csv")
    ann = ann[(ann["Valid Label"] == True) & (ann["Valid Reasoning"] == True)]  # noqa: E712
    ann["Label"] = ann["Label"].str.strip().str.lower()
    ann = ann[ann["Label"].isin(LABEL_MAP)]
    ann["evidence"] = ann["Annotations"].fillna("").astype(str).map(
        lambda s: re.sub(r"\s+", " ", html.unescape(html.unescape(s))).strip())
    ann = ann[ann["evidence"].str.len().between(100, 1200)]
    ann = ann[ann["evidence"].map(prose_ratio) >= 0.60]
    agree = ann.groupby("PromptID")["Label"].nunique()
    ann = ann[ann["PromptID"].isin(agree[agree == 1].index)]
    per = ann.sort_values("evidence", key=lambda s: s.str.len(), ascending=False) \
        .drop_duplicates("PromptID")
    m = per.merge(prompts, on=["PromptID", "PMCID"])
    for c in ["Intervention", "Comparator", "Outcome"]:
        m[c] = m[c].fillna("").astype(str).str.strip()
    m = m[(m["Intervention"] != "") & (m["Comparator"] != "") & (m["Outcome"] != "")]
    m["gold_label"] = m["Label"].map(LABEL_MAP)
    pools = {}
    for s in samples:
        g = m[(m["PMCID"] == s["pmcid"]) & (m["PromptID"] != s["target"]["prompt_id"])]
        rows = [{"prompt_id": int(r["PromptID"]), "intervention": r["Intervention"],
                 "comparator": r["Comparator"], "outcome": r["Outcome"],
                 "evidence": r["evidence"], "gold_label": r["gold_label"]}
                for _, r in g.sort_values("PromptID").iterrows()]
        random.Random(f"{s['sample_id']}-K").shuffle(rows)
        pools[s["sample_id"]] = rows
    return pools


# ------------------------------------------------------------------ paraphrases
async def paraphrases(sample, cache, sem):
    """One paraphrase per distractor slot, length-matched to that distractor.
    Two candidates per slot so verification can fall back."""
    out = []
    for i, d in enumerate(sample["distractors"]):
        words = max(20, int(len(d["evidence"].split()) * 1.0))
        for cand in range(2):
            key = full_cache_key("gpt-5.4-mini", {"task": "p4_paraphrase", "sid": sample["sample_id"],
                                                  "slot": i, "cand": cand,
                                                  "text": sample["target"]["evidence"]})
            text = (await chat("gpt-5.4-mini",
                               [{"role": "system", "content": PARA_SYSTEM},
                                {"role": "user", "content": PARA_USER.format(
                                    text=sample["target"]["evidence"], words=words)}],
                               cache=cache, cache_key=key, sem=sem, temperature=1.0,
                               seed=42 + cand, max_tokens=600)).strip()
            out.append({"slot": i, "cand": cand, "text": text, "tokens": ntok(text)})
    return out


async def build(samples):
    rng = random.Random(SEED)
    pools = build_kpools(samples)
    cache = LLMCache("cache/phase4_materials.jsonl")
    sem = asyncio.Semaphore(16)
    rows = {}
    for s in samples:
        rows[s["sample_id"]] = {
            "sample_id": s["sample_id"], "pmcid": s["pmcid"],
            "K": 1 + len(s["distractors"]),
            "multi_tokens": ntok(s["target"]["evidence"]) + sum(ntok(d["evidence"]) for d in s["distractors"]),
            "filler_chunks": make_filler(s, random.Random(f"{s['sample_id']}-filler")),
            "kpool": pools[s["sample_id"]],
        }
    paras = await asyncio.gather(*[paraphrases(s, cache, sem) for s in samples])
    for s, p in zip(samples, paras):
        rows[s["sample_id"]]["dup_candidates"] = p
        rows[s["sample_id"]]["dup_chunks"] = None      # set by verify
    OUT.parent.mkdir(exist_ok=True)
    with open(OUT, "w") as f:
        for r in rows.values():
            f.write(json.dumps(r, ensure_ascii=False) + "\n")
    n_fill = sum(r["filler_chunks"] is not None for r in rows.values())
    n_k5 = sum(len(r["kpool"]) >= 4 for r in rows.values())
    print(f"materials: {len(rows)} articles; filler available {n_fill}; K=5-capable {n_k5}")
    ft = [r["filler_chunks"] for r in rows.values() if r["filler_chunks"]]
    err = [abs(sum(ntok(c) for c in r["filler_chunks"]) - (r["multi_tokens"] - ntok(
        next(s for s in samples if s["sample_id"] == r["sample_id"])["target"]["evidence"])))
        for r in rows.values() if r["filler_chunks"]]
    print(f"filler token mismatch: mean |err| = {sum(err) / max(len(err), 1):.1f} tokens")


async def verify(samples):
    from supdrift.classifier import classify
    rows = {json.loads(l)["sample_id"]: json.loads(l) for l in open(OUT)}
    cache = LLMCache("cache/phase4_materials_verify.jsonl")
    sem = asyncio.Semaphore(32)
    smap = {s["sample_id"]: s for s in samples}

    async def one(sid):
        s, r = smap[sid], rows[sid]
        t = s["target"]
        for c in r["dup_candidates"]:
            if "verdict" in c:
                continue
            res = await classify(t["intervention"], t["comparator"], t["outcome"], c["text"],
                                 cache=cache, sem=sem)
            c["verdict"] = res["claim_label"]
            c["grounded"] = res["claim_label"] == t["gold_label"]
        chunks = []
        for i in range(len(s["distractors"])):
            ok = [c for c in r["dup_candidates"] if c["slot"] == i and c.get("grounded")]
            if not ok:
                chunks = None
                break
            chunks.append(ok[0]["text"])
        r["dup_chunks"] = chunks
    await asyncio.gather(*[one(sid) for sid in rows])
    with open(OUT, "w") as f:
        for r in rows.values():
            f.write(json.dumps(r, ensure_ascii=False) + "\n")
    cands = [c for r in rows.values() for c in r["dup_candidates"]]
    print(f"paraphrases grounded: {sum(c['grounded'] for c in cands)}/{len(cands)}; "
          f"articles with a full dup set: {sum(r['dup_chunks'] is not None for r in rows.values())}")


if __name__ == "__main__":
    ap = argparse.ArgumentParser()
    ap.add_argument("cmd", choices=["build", "verify"])
    args = ap.parse_args()
    samples = [json.loads(l) for l in open("data/gate2/gate2_v1.jsonl")]
    asyncio.run(build(samples) if args.cmd == "build" else verify(samples))
